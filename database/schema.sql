-- Do Do Tea Shop - MySQL Schema
-- Naming: tbl_*, PK_*, FK_*

CREATE DATABASE IF NOT EXISTS do_do_tea_shop
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE do_do_tea_shop;

SET FOREIGN_KEY_CHECKS = 0;

DROP TABLE IF EXISTS tbl_CHI_TIET_KHUYEN_MAI;
DROP TABLE IF EXISTS tbl_KHUYEN_MAI;
DROP TABLE IF EXISTS tbl_CONG_THUC;
DROP TABLE IF EXISTS tbl_CHI_TIET_PHIEU_NHAP;
DROP TABLE IF EXISTS tbl_PHIEU_NHAP;
DROP TABLE IF EXISTS tbl_NGUYEN_LIEU;
DROP TABLE IF EXISTS tbl_HOA_DON;
DROP TABLE IF EXISTS tbl_CHI_TIET_DON_HANG;
DROP TABLE IF EXISTS tbl_DON_HANG;
DROP TABLE IF EXISTS tbl_DO_UONG;
DROP TABLE IF EXISTS tbl_DANH_MUC;
DROP TABLE IF EXISTS tbl_KHACH_HANG;
DROP TABLE IF EXISTS tbl_NHAN_VIEN;

SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE tbl_NHAN_VIEN (
  PK_NHAN_VIEN INT AUTO_INCREMENT PRIMARY KEY,
  hoTen VARCHAR(255) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  matKhauHash VARCHAR(255) NOT NULL,
  vaiTro ENUM('ADMIN','MANAGER','STAFF') NOT NULL DEFAULT 'STAFF',
  trangThai TINYINT NOT NULL DEFAULT 1,
  ngayTao DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE tbl_KHACH_HANG (
  PK_KHACH_HANG INT AUTO_INCREMENT PRIMARY KEY,
  hoTen VARCHAR(255) NOT NULL,
  soDienThoai VARCHAR(30) NULL,
  diemTichLuy INT NOT NULL DEFAULT 0,
  trangThai TINYINT NOT NULL DEFAULT 1
) ENGINE=InnoDB;

CREATE TABLE tbl_DANH_MUC (
  PK_DANH_MUC INT AUTO_INCREMENT PRIMARY KEY,
  tenDanhMuc VARCHAR(255) NOT NULL,
  trangThai TINYINT NOT NULL DEFAULT 1
) ENGINE=InnoDB;

CREATE TABLE tbl_DO_UONG (
  PK_DO_UONG INT AUTO_INCREMENT PRIMARY KEY,
  FK_DANH_MUC INT NOT NULL,
  tenDoUong VARCHAR(255) NOT NULL,
  giaBan DECIMAL(12,0) NOT NULL,
  hinhAnhUrl VARCHAR(500) NULL,
  dangBan TINYINT NOT NULL DEFAULT 1,
  CONSTRAINT FK_DO_UONG_DANH_MUC FOREIGN KEY (FK_DANH_MUC) REFERENCES tbl_DANH_MUC(PK_DANH_MUC)
) ENGINE=InnoDB;

CREATE TABLE tbl_DON_HANG (
  PK_DON_HANG INT AUTO_INCREMENT PRIMARY KEY,
  FK_NHAN_VIEN INT NOT NULL,
  trangThai ENUM('CHO_THANH_TOAN','HOAN_THANH','HUY') NOT NULL DEFAULT 'CHO_THANH_TOAN',
  tongTien DECIMAL(12,0) NOT NULL DEFAULT 0,
  giamGia DECIMAL(12,0) NOT NULL DEFAULT 0,
  thanhTien DECIMAL(12,0) NOT NULL DEFAULT 0,
  ghiChu VARCHAR(500) NULL,
  ngayTao DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ngayHoanThanh DATETIME NULL,
  CONSTRAINT FK_DON_HANG_NHAN_VIEN FOREIGN KEY (FK_NHAN_VIEN) REFERENCES tbl_NHAN_VIEN(PK_NHAN_VIEN)
) ENGINE=InnoDB;

CREATE TABLE tbl_CHI_TIET_DON_HANG (
  PK_CTDH INT AUTO_INCREMENT PRIMARY KEY,
  FK_DON_HANG INT NOT NULL,
  FK_DO_UONG INT NOT NULL,
  soLuong INT NOT NULL,
  donGia DECIMAL(12,0) NOT NULL,
  ghiChu VARCHAR(255) NULL,
  thanhTien DECIMAL(12,0) NOT NULL,
  CONSTRAINT FK_CTDH_DON_HANG FOREIGN KEY (FK_DON_HANG) REFERENCES tbl_DON_HANG(PK_DON_HANG),
  CONSTRAINT FK_CTDH_DO_UONG FOREIGN KEY (FK_DO_UONG) REFERENCES tbl_DO_UONG(PK_DO_UONG)
) ENGINE=InnoDB;

CREATE TABLE tbl_HOA_DON (
  PK_HOA_DON INT AUTO_INCREMENT PRIMARY KEY,
  FK_DON_HANG INT NOT NULL UNIQUE,
  phuongThuc ENUM('TIEN_MAT','CHUYEN_KHOAN') NOT NULL,
  soTienKhachDua DECIMAL(12,0) NOT NULL DEFAULT 0,
  soTienThua DECIMAL(12,0) NOT NULL DEFAULT 0,
  ngayThanhToan DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT FK_HOA_DON_DON_HANG FOREIGN KEY (FK_DON_HANG) REFERENCES tbl_DON_HANG(PK_DON_HANG)
) ENGINE=InnoDB;

CREATE TABLE tbl_NGUYEN_LIEU (
  PK_NGUYEN_LIEU INT AUTO_INCREMENT PRIMARY KEY,
  tenNguyenLieu VARCHAR(255) NOT NULL,
  donViTinh VARCHAR(50) NOT NULL,
  soLuongTon DECIMAL(12,2) NOT NULL DEFAULT 0,
  nguongToiThieu DECIMAL(12,2) NOT NULL DEFAULT 0,
  trangThai TINYINT NOT NULL DEFAULT 1
) ENGINE=InnoDB;

CREATE TABLE tbl_PHIEU_NHAP (
  PK_PHIEU_NHAP INT AUTO_INCREMENT PRIMARY KEY,
  FK_NHAN_VIEN INT NOT NULL,
  nhaCungCap VARCHAR(255) NULL,
  tongTien DECIMAL(12,0) NOT NULL DEFAULT 0,
  ngayNhap DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ghiChu VARCHAR(500) NULL,
  CONSTRAINT FK_PHIEU_NHAP_NHAN_VIEN FOREIGN KEY (FK_NHAN_VIEN) REFERENCES tbl_NHAN_VIEN(PK_NHAN_VIEN)
) ENGINE=InnoDB;

CREATE TABLE tbl_CHI_TIET_PHIEU_NHAP (
  PK_CTPN INT AUTO_INCREMENT PRIMARY KEY,
  FK_PHIEU_NHAP INT NOT NULL,
  FK_NGUYEN_LIEU INT NOT NULL,
  soLuong DECIMAL(12,2) NOT NULL,
  donGia DECIMAL(12,0) NOT NULL,
  thanhTien DECIMAL(12,0) NOT NULL,
  CONSTRAINT FK_CTPN_PHIEU_NHAP FOREIGN KEY (FK_PHIEU_NHAP) REFERENCES tbl_PHIEU_NHAP(PK_PHIEU_NHAP),
  CONSTRAINT FK_CTPN_NGUYEN_LIEU FOREIGN KEY (FK_NGUYEN_LIEU) REFERENCES tbl_NGUYEN_LIEU(PK_NGUYEN_LIEU)
) ENGINE=InnoDB;

CREATE TABLE tbl_CONG_THUC (
  PK_CONG_THUC INT AUTO_INCREMENT PRIMARY KEY,
  FK_DO_UONG INT NOT NULL,
  FK_NGUYEN_LIEU INT NOT NULL,
  dinhLuong DECIMAL(12,2) NOT NULL,
  CONSTRAINT FK_CONG_THUC_DO_UONG FOREIGN KEY (FK_DO_UONG) REFERENCES tbl_DO_UONG(PK_DO_UONG),
  CONSTRAINT FK_CONG_THUC_NGUYEN_LIEU FOREIGN KEY (FK_NGUYEN_LIEU) REFERENCES tbl_NGUYEN_LIEU(PK_NGUYEN_LIEU)
) ENGINE=InnoDB;

CREATE TABLE tbl_KHUYEN_MAI (
  PK_KHUYEN_MAI INT AUTO_INCREMENT PRIMARY KEY,
  tenKhuyenMai VARCHAR(255) NOT NULL,
  phanTramGiam DECIMAL(5,2) NOT NULL,
  tuNgay DATETIME NOT NULL,
  denNgay DATETIME NOT NULL,
  trangThai TINYINT NOT NULL DEFAULT 1
) ENGINE=InnoDB;

CREATE TABLE tbl_CHI_TIET_KHUYEN_MAI (
  PK_CHI_TIET_KM INT AUTO_INCREMENT PRIMARY KEY,
  FK_KHUYEN_MAI INT NOT NULL,
  FK_DO_UONG INT NOT NULL,
  CONSTRAINT FK_CTKM_KHUYEN_MAI FOREIGN KEY (FK_KHUYEN_MAI) REFERENCES tbl_KHUYEN_MAI(PK_KHUYEN_MAI),
  CONSTRAINT FK_CTKM_DO_UONG FOREIGN KEY (FK_DO_UONG) REFERENCES tbl_DO_UONG(PK_DO_UONG)
) ENGINE=InnoDB;

